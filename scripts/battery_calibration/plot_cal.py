cal_file = open("factory.bat_cal", "wb")

def write_cal_header(f, tolerance, percent_points, current_points):
    signature = b"bsbbcal\x00"
    i_range = 3000
    f.write(struct.pack("<8sHHHH", signature, tolerance, i_range, percent_points, current_points))

write_cal_header(cal_file, 5, Z.shape[1], Z.shape[0])

if PRINT_RAW_DATA:
    for curve in CAL:
        for percent, (a, v) in enumerate(curve):
            i_bkt = min(60, max(0, round(a * 10) + 30))
            Z[i_bkt, percent] = v

else:
    for p in range(101):
        fit_x = []
        fit_y = []
        for curve in CAL:
            a, v = curve[p]
            fit_x.append(a)
            fit_y.append(v)
        poly = np.polyfit(fit_x, fit_y, POLY_DEG)
        for i in Y_raw:
            Z[round(i * 10) + 30, p] = min(4.5, max(0, np.polyval(poly, i)))

    for i in range(61):
        last_mv = 0
        for p in range(101):
            mv = round(Z[i, p] * 1000)
            if p < 2 or p >= 99:
                cal_file.write(struct.pack("<H", mv))
            else:
                delta = mv - last_mv
                if delta not in range(-128, 128):
                    print(f"warn: Ibkt={i}, %={p}: delta clipped")
                    delta = min(127, max(-128, delta))
                cal_file.write(struct.pack("<b", delta))
            last_mv = mv

cal_file.close()

