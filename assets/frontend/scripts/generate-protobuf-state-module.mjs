import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import protobuf from 'protobufjs';

const { Root } = protobuf;

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendDir = resolve(scriptDir, '..');

const getRepoRoot = () => {
  try {
    return execFileSync('git', ['rev-parse', '--show-toplevel'], {
      cwd: frontendDir,
      encoding: 'utf8'
    }).trim();
  } catch {
    return null;
  }
};

const inputProtoCandidates = [
  resolve(frontendDir, '..', 'proto', 'state.proto')
];

const repoRoot = getRepoRoot();
if (repoRoot) {
  inputProtoCandidates.push(resolve(repoRoot, 'assets', 'proto', 'state.proto'));
}

const inputProto = inputProtoCandidates.find(candidate => existsSync(candidate));
if (!inputProto) {
  throw new Error(`Unable to locate assets/proto/state.proto. Checked: ${inputProtoCandidates.join(', ')}`);
}

const outputModule = resolve(frontendDir, 'generated', 'protobuf', 'stateDescriptor.ts');

const root = new Root();
root.loadSync(inputProto);
root.resolveAll();

const descriptor = JSON.stringify(root.toJSON(), null, 2);
const moduleSource = `/* eslint-disable @stylistic/quotes */\n// This file is generated by scripts/generate-protobuf-state-module.mjs.\nexport default ${descriptor} as const;\n`;

mkdirSync(dirname(outputModule), { recursive: true });
writeFileSync(outputModule, moduleSource);
